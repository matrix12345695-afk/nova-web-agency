'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const url=process.env.TEST_POSTGRES_URL;
test('PostgreSQL CRM survives module reload and records status history', {skip:!url},async()=>{
 process.env.DATABASE_URL=url;
 delete require.cache[require.resolve('../crm')];
 const crm=require('../crm');
 await crm.init();
 assert.equal(crm.mode(),'postgres');
 const lead=crm.create({name:'Postgres CI mock',contact:'TEST ONLY',type:'GROW',notes:'No actual customer'});
 lead.id='NWCI'+crypto.randomBytes(6).toString('hex');
 assert.equal(await crm.add(lead),true);
 assert.equal(await crm.add(lead),false);
 assert.equal((await crm.get(lead.id)).status,'new');
 const updated=await crm.change(lead.id,'working');
 assert.equal(updated.status,'working');
 assert.equal(updated.history.length,2);
 assert.equal(await crm.change(lead.id,'working').then(x=>x.history.length),2);
 const sample=await crm.summary();
 assert.ok(sample.total>=1);
 await crm.markUpdateProcessed(8675309);
 assert.equal(await crm.isUpdateProcessed(8675309),true);
 delete require.cache[require.resolve('../crm')];
 const reloaded=require('../crm');
 await reloaded.init();
 const persisted=await reloaded.get(lead.id);
 assert.equal(persisted.status,'working');
 assert.equal(persisted.history.length,2);
});
